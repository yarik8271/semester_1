# 1. Перша програма кожного програміста
print("Hello, World!")

# 2. Створення змінних усіх типів із конспекту
age = 10                       # int (ціле число)
pi_val = 4.19                  # float (число з комою)
name = "ярик"                 # str (текстовий рядок)
is_valid = True                # bool (булеве значення)
lst = [1, 2, 3]                # list (список)
tpl = (1, 2)                   # tuple (кортеж / незмінний перелік)
dct = {"10": 41, "11": 21}     # dict (словник / пари ключ:значення)
st = {1, 2, 3, 4, 5}           # set (множина)

# 3. Виведення значення кожної змінної та її типу
print("Значення:", age, "| Тип:", type(age))
print("Значення:", pi_val, "| Тип:", type(pi_val))
print("Значення:", name, "| Тип:", type(name))
print("Значення:", is_valid, "| Тип:", type(is_valid))
print("Значення:", lst, "| Тип:", type(lst))
print("Значення:", tpl, "| Тип:", type(tpl))
print("Значення:", dct, "| Тип:", type(dct))
print("Значення:", st, "| Тип:", type(st))

# 4. Використання вивчених операторів (+, //, %)
a = 17
b = 5

print("Додавання (a + b)=", a + b)
print("Ціле ділення (a // b)=", a // b)
print("Остача від ділення (a % b)=", a % b)