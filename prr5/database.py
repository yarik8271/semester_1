def generate_ingredients_pool():
    """Генерує мінімум 200 унікальних інгредієнтів."""
    try:
        prefixes = ["Місячний", "Сонячний", "Лісовий", "Озерний", "Печерний", "Огняний", "Крижаний", "Тіньовий",
                    "Драконячий", "Древній"]
        bases = ["Корінь", "Квітка", "Лист", "Гриб", "Плід", "Пилок", "Кристал", "Руда", "Камінь", "Сльоза", "Перо",
                 "Хвіст", "Ікла", "Луска", "Желч", "Жало", "Сік", "Кора", "Мох", "Ягода"]

        ingredients = []
        for p in prefixes:
            for b in bases:
                name = f"{p} {b}"
                if name not in ingredients:
                    ingredients.append(name)
        return ingredients[:200]
    except Exception as e:
        print(f"[Помилка генерації інгредієнтів]: {e}")
        return ["Базовий Трав'яний корінь"]


